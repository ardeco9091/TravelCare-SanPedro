-- Esquema inicial de TravelCare. Ejecutar en Supabase SQL Editor.
create table if not exists public.places (
  id bigint generated by default as identity primary key,
  nombre text not null,
  categoria text not null check (categoria in ('alojamiento', 'salud', 'transporte')),
  categoria_label text not null,
  direccion text not null,
  estado text not null,
  abierto_ahora boolean not null default true,
  destacado boolean not null default false,
  promocion text,
  notas text not null default '',
  telefono text,
  whatsapp text,
  lat double precision not null,
  lng double precision not null
);

create table if not exists public.project_settings (
  id text primary key check (id = 'main'),
  integrantes text not null,
  institucion text not null,
  destino text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.places enable row level security;
alter table public.project_settings enable row level security;
alter table public.admin_users enable row level security;

create or replace function public.is_travelcare_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.admin_users as admins
    where admins.user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_travelcare_admin() from public;
grant execute on function public.is_travelcare_admin() to authenticated;

grant select on public.places, public.project_settings to anon, authenticated;
grant insert, update, delete on public.places, public.project_settings to authenticated;
revoke all on public.admin_users from anon, authenticated;

drop policy if exists "Anyone can read places" on public.places;
create policy "Anyone can read places"
  on public.places for select to anon, authenticated using (true);

drop policy if exists "TravelCare admins manage places" on public.places;
create policy "TravelCare admins manage places"
  on public.places for all to authenticated
  using ((select public.is_travelcare_admin()))
  with check ((select public.is_travelcare_admin()));

drop policy if exists "Anyone can read project settings" on public.project_settings;
create policy "Anyone can read project settings"
  on public.project_settings for select to anon, authenticated using (true);

drop policy if exists "TravelCare admins manage project settings" on public.project_settings;
create policy "TravelCare admins manage project settings"
  on public.project_settings for all to authenticated
  using ((select public.is_travelcare_admin()))
  with check ((select public.is_travelcare_admin()));

